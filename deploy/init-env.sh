#!/usr/bin/env bash
# Generate /srv/apps/ventmail/.env on the mail box. Run once, before the first deploy.
#
#   init-env.sh <tag>
#
# Secrets are generated here and written straight to the file (mode 600); none
# is ever printed. APP_KEY and AUDIT_PEPPER come from the release image.
# Database credentials come from db.env (venture-infra new-app-db.sh). Secrets
# that arrive later from another box (the ventSSO client secret) or from the
# Postal instances (API keys, webhook public keys) go in with set-env.sh.
# Idempotent: an existing .env is never touched; delete it deliberately to redo.
#
# The sending switches start CLOSED (deploy rule 3): SENDING_LIVE=false, marketing
# off, the seed allowlist enforced. Only the owner flips them (RUNBOOK-mail §13).
set -euo pipefail

IMAGE="ghcr.io/venture-co-group/ventmail"
APP_DIR="${APP_DIR:-$(cd "$(dirname "$0")" && pwd)}"
APP_HOST="${APP_HOST:-app.ventmail.app}"
API_HOST="${API_HOST:-api.ventmail.app}"
LANDING_HOST="${LANDING_HOST:-ventmail.app}"
ISSUER="${ISSUER:-https://sso.ventureco.app}"
# The edge Caddy's fixed addresses on the dual-stack edge network (venture-infra box.env).
EDGE_PROXY="${EDGE_PROXY:-172.30.0.2/32 fd30:0:0:1::2/128}"
SEED_ALLOWLIST="${SEED_ALLOWLIST:?SEED_ALLOWLIST (comma-separated seed addresses) is required}"

log() { printf '%s [init-env] %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*" >&2; }

tag="${1:-}"
[[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$ || "$tag" =~ ^[0-9a-f]{40}$ ]] ||
    { echo "usage: init-env.sh <tag>" >&2; exit 2; }
cd "$APP_DIR"
umask 077

if [ -f .env ]; then
    log ".env already exists; left untouched"
    exit 0
fi
[ -f db.env ] || { log "db.env missing: run new-app-db.sh ventmail first"; exit 1; }

artisan() { docker run --rm --entrypoint php "$IMAGE:$tag" artisan "$@" --no-ansi; }
app_key="$(artisan key:generate --show | tr -d '[:space:]')"
[[ "$app_key" == base64:* ]] || { log "could not obtain APP_KEY from $IMAGE:$tag"; exit 1; }
pepper="$(artisan ventmail:pepper | tr -d '[:space:]')"
[ "${#pepper}" -ge 32 ] || { log "could not obtain AUDIT_PEPPER from $IMAGE:$tag"; exit 1; }

tmp="$(mktemp .env.XXXXXX)"
trap 'rm -f "$tmp"' EXIT
{
    cat <<ENV
# Generated by init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Secrets: never copy out of this box.
APP_NAME=ventMail
APP_ENV=production
APP_KEY=$app_key
APP_DEBUG=false
APP_URL=https://$APP_HOST
APP_LOCALE=hu
APP_FALLBACK_LOCALE=en
LOG_CHANNEL=stderr
LOG_LEVEL=info
AUDIT_PEPPER=$pepper

# --- behind the mail-box edge
TRUSTED_PROXIES="$EDGE_PROXY"
# ventmail-web: the Postal webhooks arrive on the internal network under this name.
TRUSTED_HOSTS=$APP_HOST,$API_HOST,$LANDING_HOST,ventmail-web
LANDING_HOST=$LANDING_HOST
SESSION_COOKIE=__Host-ventmail_session
SESSION_SECURE_COOKIE=true
SESSION_SAME_SITE=lax

# --- identity: ventSSO (client id + secret arrive via set-env.sh)
OIDC_PROVIDER_URL=$ISSUER
OIDC_CLIENT_ID=
OIDC_CLIENT_SECRET=
OIDC_SCOPES="openid profile email"
OIDC_ROLES_CLAIM=resource_access.ventmail.roles
IDENTITY_DEV_LOGIN=false

# --- redis (stack-local, password protected)
REDIS_CLIENT=phpredis
REDIS_HOST=redis
REDIS_PORT=6379
REDIS_PASSWORD=$(openssl rand -hex 32)
SESSION_DRIVER=redis
SESSION_LIFETIME=120
CACHE_STORE=redis
QUEUE_CONNECTION=redis

# --- not part of v1 on this box (docs/plans/deploy-ovh.md)
BROADCAST_CONNECTION=log
SCOUT_DRIVER=null
MEILISEARCH_HOST=
INBOUND_ENABLED=false
SMTP_SUBMISSION_ENABLED=false
MAIL_MAILER=log

# --- sending: CLOSED until the owner opens it (RUNBOOK-mail §13)
SENDING_DRIVER=postal
SENDING_LIVE=false
SENDING_MARKETING_ENABLED=false
SEND_ALLOWLIST_ENFORCED=true
SEND_ALLOWLIST=$SEED_ALLOWLIST
SENDING_DISPATCH_VIA_QUEUE=true
# Only the ventPay/ventOS fakes remain (not live yet); consent and risk are real.
SENDING_ALLOW_FAKE_DEPENDENCIES=true
SENDING_TRACKING_BASE_URL=https://$APP_HOST
DOMAINS_RESOLVER=system

# --- the two Postal instances (keys arrive via set-env.sh)
POSTAL_TX_ENDPOINT=http://postal-tx-web:5000
POSTAL_TX_API_KEY=
POSTAL_TX_WEBHOOK_PUBLIC_KEY=
POSTAL_MK_ENDPOINT=http://postal-mk-web:5000
POSTAL_MK_API_KEY=
POSTAL_MK_WEBHOOK_PUBLIC_KEY=

# --- database (internal mail-db network only)
DB_SSLMODE=disable
ENV
    cat db.env
} >"$tmp"
chmod 600 "$tmp"
mv "$tmp" .env
trap - EXIT
unset app_key pepper
log ".env written (mode 600)"
